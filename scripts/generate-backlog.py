#!/usr/bin/env python3
"""Generate docs/backlog.md from docs/epics/E*.md.

The epic files are the source of truth. Edit them, then run:
    python3 scripts/generate-backlog.py
"""
import glob
import re
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
TASK_RE = re.compile(r"^### (\S+) · (.+?) — `(\w)`\n(.*?)(?=^### |\Z)", re.M | re.S)


def main() -> None:
    epics = []
    for path in sorted(glob.glob(str(DOCS / "epics" / "E*.md"))):
        text = Path(path).read_text()
        title = text.splitlines()[0][2:]
        goal = re.search(r"\*\*Goal:\*\* (.*)", text).group(1)
        milestone = re.search(r"\*\*Milestone:\*\* (.*)", text).group(1)
        tasks = []
        for m in TASK_RE.finditer(text):
            body = m[4].strip().replace("](../", "](")
            deps = re.search(r"^\*\*Depends on:\*\* (.*)$", body, re.M)
            tasks.append((m[1], m[2], m[3], deps[1] if deps else "—", body))
        epics.append((Path(path).name, title, goal, milestone, tasks))

    small = sum(t[2] == "S" for e in epics for t in e[4])
    medium = sum(t[2] == "M" for e in epics for t in e[4])

    out = [
        "# Backlog",
        "",
        "<!-- Generated by scripts/generate-backlog.py from docs/epics/*.md. Do not edit by hand. -->",
        "",
        "Every task with its description, scope and acceptance criteria. "
        "Sizes: **S** ≤ 1 day, **M** 1–3 days. "
        "The [Definition of Done](roadmap.md#definition-of-done) applies to every task.",
        "",
        f"**Totals:** {small + medium} tasks ({small} × S, {medium} × M), "
        f"roughly {small + medium * 2} developer-days (S = 1, M = 2).",
        "",
        "## Overview",
        "",
        "| ID | Task | Size | Depends on |",
        "|---|---|---|---|",
    ]
    for _, _, _, _, tasks in epics:
        for tid, name, size, deps, _ in tasks:
            anchor = re.sub(r"[^a-z0-9 -]", "", f"{tid} · {name} — {size}".lower()).replace(" ", "-")
            out.append(f"| {tid} | [{name}](#{anchor}) | {size} | {deps} |")
    out.append("")

    for fname, title, goal, milestone, tasks in epics:
        out += [
            "---",
            "",
            f"## {title}",
            "",
            f"**Goal:** {goal}  ",
            f"**Milestone:** {milestone}  ",
            f"**Source:** [epics/{fname}](epics/{fname})",
            "",
        ]
        for tid, name, size, _, body in tasks:
            out += [f"### {tid} · {name} — {size}", "", body, ""]

    (DOCS / "backlog.md").write_text("\n".join(out))
    print(f"Wrote docs/backlog.md: {len(epics)} epics, {small + medium} tasks")


if __name__ == "__main__":
    main()
